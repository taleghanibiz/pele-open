  created_at timestamptz not null default now());

create table public.contacts (
  id uuid primary key default gen_random_uuid(),
  team_id smallint not null references public.teams on delete cascade,
  company_id uuid references public.companies on delete set null,
  name text not null check (length(name) between 1 and 120),
  role text not null default '',
  phone text not null default '' check (phone = '' or phone ~ '^\+\d{6,15}$'),  -- normalised by js normPhone (future PBX match)
  email text not null default '',
  notes text not null default '',
  created_by text not null default public.me(),
  created_at timestamptz not null default now());
create index contacts_phone on public.contacts (phone) where phone <> '';

create table public.card_contacts (
  card_id uuid references public.cards on delete cascade,
  contact_id uuid references public.contacts on delete cascade,
  primary key (card_id, contact_id));

