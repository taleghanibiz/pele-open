-- ===== self-hosting: admins create boards; the first sign-in becomes admin =====
create or replace function public.create_team(n text, c text default '#FFC21A') returns smallint language plpgsql security definer
set search_path = public
as $$
declare t smallint;
begin
  if not is_admin() then raise exception 'only admins can create boards'; end if;
  if btrim(coalesce(n, '')) = '' or c !~ '^#[0-9A-Fa-f]{6}$' then raise exception 'bad board name or color'; end if;
  insert into teams (name, color) values (left(btrim(n), 40), c) returning id into t;
  insert into team_members values (t, me());
  insert into columns (team_id, title, position) values (t, 'برای انجام', 1024), (t, 'در حال انجام', 2048), (t, 'انجام شد', 3072);
  return t;
end $$;

-- nobody is invited yet → whoever signs in first owns the install
create or replace function public.bootstrap() returns boolean language plpgsql security definer
set search_path = public
as $$
begin
  if me() = '' then return false; end if;
  lock table members in exclusive mode;  -- two first sign-ins at once: only one wins
  if exists (select 1 from members) then return false; end if;
  insert into members (email, is_admin) values (me(), true);
  perform create_team('تیم من', '#FFC21A');
  return true;
end $$;

-- the app shows the installer's contact form only on a fresh install
create or replace function public.is_fresh() returns boolean language sql stable security definer
set search_path = public
as $$ select not exists (select 1 from members) $$;

revoke execute on function public.create_team(text, text), public.bootstrap(), public.is_fresh() from public, anon;
grant execute on function public.create_team(text, text), public.bootstrap(), public.is_fresh() to authenticated;

