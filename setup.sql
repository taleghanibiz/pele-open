-- ===== 001_schema =====
create or replace function public.me() returns text language sql stable
as $$ select lower(coalesce(auth.jwt() ->> 'email', '')) $$;

create table public.members (
  email text primary key check (email = lower(email) and email like '%@%'),
  name text not null default '',
  is_admin boolean not null default false,
  telegram_chat_id bigint unique,
  created_at timestamptz not null default now());

create table public.teams (id smallint generated by default as identity primary key, name text not null, color text not null,
  personal boolean not null default false);

create table public.team_members (
  team_id smallint references public.teams on delete cascade,
  email text references public.members on delete cascade on update cascade,
  primary key (team_id, email));

create table public.columns (
  id uuid primary key default gen_random_uuid(),
  team_id smallint not null references public.teams on delete cascade,
  title text not null check (length(title) between 1 and 60),
  position double precision not null default 0,
  unique (id, team_id));

create table public.cards (
  id uuid primary key default gen_random_uuid(),
  team_id smallint not null references public.teams on delete cascade,
  column_id uuid,
  kind text not null default 'task' check (kind in ('task', 'meeting')),
  title text not null check (length(title) between 1 and 200),
  description text not null default '',
  due_date date,
  progress smallint not null default 0 check (progress between 0 and 100),
  position double precision not null default 0,
  created_by text not null default public.me(),
  updated_at timestamptz not null default now(),
  foreign key (column_id, team_id) references public.columns (id, team_id) on delete restrict,
  check (kind = 'meeting' or column_id is not null));

create table public.card_assignees (
  card_id uuid references public.cards on delete cascade,
  email text references public.members on delete cascade on update cascade,
  added_by text not null default public.me(),
  primary key (card_id, email));

create table public.comments (
  id uuid primary key default gen_random_uuid(),
  card_id uuid not null references public.cards on delete cascade,
  author text not null default public.me(),
  body text not null check (length(body) between 1 and 4000),
  created_at timestamptz not null default now());

create table public.attachments (
  id uuid primary key default gen_random_uuid(),
  card_id uuid not null references public.cards on delete cascade,
  path text not null unique,
  name text not null,
  size bigint not null,
  mime text not null default '',
  uploaded_by text not null default public.me(),
  created_at timestamptz not null default now());

create table public.telegram_codes (
  code text primary key check (length(code) >= 12),
  email text not null default public.me() references public.members on delete cascade,
  expires_at timestamptz not null default now() + interval '10 minutes');

create or replace function public.touch() returns trigger language plpgsql
as $$ begin new.updated_at = now(); return new; end $$;
create trigger cards_touch before update on public.cards for each row execute function public.touch();

-- ===== 002_rls =====
create or replace function public.is_member() returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from members where email = me()) $$;
create or replace function public.is_admin() returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from members where email = me() and is_admin) $$;
create or replace function public.in_team(t smallint) returns boolean language sql stable security definer set search_path = public
as $$ select is_admin() or exists (select 1 from team_members where team_id = t and email = me()) $$;
create or replace function public.card_team(c uuid) returns smallint language sql stable security definer set search_path = public
as $$ select team_id from cards where id = c $$;
create or replace function public.shares_team(e text) returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from team_members a join team_members b using (team_id) where a.email = me() and b.email = e) $$;

alter table members enable row level security;
alter table teams enable row level security;
alter table team_members enable row level security;
alter table columns enable row level security;
alter table cards enable row level security;
alter table card_assignees enable row level security;
alter table comments enable row level security;
alter table attachments enable row level security;
alter table telegram_codes enable row level security;

create policy m_read on members for select to authenticated using (email = me() or is_admin() or shares_team(email));
create policy m_admin on members for all to authenticated using (is_admin()) with check (is_admin());

create policy t_read on teams for select to authenticated using (in_team(id));
create policy t_admin on teams for all to authenticated using (is_admin()) with check (is_admin());

create policy tm_read on team_members for select to authenticated using (in_team(team_id));
create policy tm_admin on team_members for all to authenticated using (is_admin()) with check (is_admin());

create policy col_all on columns for all to authenticated using (in_team(team_id)) with check (in_team(team_id));
create policy card_all on cards for all to authenticated using (in_team(team_id)) with check (in_team(team_id));

create policy ca_read on card_assignees for select to authenticated using (in_team(card_team(card_id)));
create policy ca_add on card_assignees for insert to authenticated with check (
  in_team(card_team(card_id)) and added_by = me()
  and exists (select 1 from team_members where team_id = card_team(card_id) and email = card_assignees.email));
create policy ca_del on card_assignees for delete to authenticated using (in_team(card_team(card_id)));

create policy cm_read on comments for select to authenticated using (in_team(card_team(card_id)));
create policy cm_add on comments for insert to authenticated with check (in_team(card_team(card_id)) and author = me());
create policy cm_own on comments for delete to authenticated using (author = me());

create policy at_read on attachments for select to authenticated using (in_team(card_team(card_id)));
create policy at_add on attachments for insert to authenticated with check (
  in_team(card_team(card_id)) and uploaded_by = me()
  and path like card_team(card_id)::text || '/' || card_id::text || '/%');
create policy at_del on attachments for delete to authenticated using (in_team(card_team(card_id)));

create policy tc_add on telegram_codes for insert to authenticated with check (email = me() and is_member());

revoke all on all tables in schema public from anon, authenticated;
grant select, insert, update, delete on members, teams, team_members, columns, cards to authenticated;
grant select, insert, delete on card_assignees, comments, attachments to authenticated;
grant insert on telegram_codes to authenticated;
grant all on all tables in schema public to service_role;

