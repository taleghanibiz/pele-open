as $$ update members set name = left(btrim(n), 60) where email = me() and name = '' and btrim(n) <> '' $$;
revoke execute on function public.claim_name(text) from public, anon;
grant execute on function public.claim_name(text) to authenticated;

-- ===== 005_meeting_reminders =====
-- meeting time (Tehran local) + which reminder (24/12/1 hours) went out last
alter table public.cards add column if not exists meet_time time, add column if not exists reminded_h smallint;

-- moving a meeting re-arms its reminders
create or replace function private.rearm() returns trigger language plpgsql as $$
begin
  if new.due_date is distinct from old.due_date or new.meet_time is distinct from old.meet_time then new.reminded_h := null; end if;
  return new;
end $$;
drop trigger if exists cards_rearm on public.cards;
create trigger cards_rearm before update on public.cards for each row execute function private.rearm();

-- every 5 minutes ask /api/remind to send due reminders
create extension if not exists pg_cron;
create or replace function private.remind_tick() returns void language plpgsql security definer set search_path = public, extensions
as $$
declare url text := replace((select value from private.config where key = 'notify_url'), '/api/notify', '/api/remind');
begin
  if url is null then return; end if;  -- Telegram not set up
  perform net.http_post(url := url, body := '{}'::jsonb,
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-webhook-secret', (select value from private.config where key = 'webhook_secret')));
end $$;
select cron.schedule('meeting-reminders', '*/5 * * * *', 'select private.remind_tick()');

