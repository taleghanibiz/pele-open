-- ===== 003_notify =====
create extension if not exists pg_net with schema extensions;
create schema if not exists private;
create table if not exists private.config (key text primary key, value text not null);
revoke all on schema private from anon, authenticated;

create or replace function private.notify_hook() returns trigger language plpgsql security definer set search_path = public, extensions
as $$
declare url text := (select value from private.config where key = 'notify_url');
        secret text := (select value from private.config where key = 'webhook_secret');
begin
  if url is null or secret is null then return new; end if;
  perform net.http_post(url := url,
    body := jsonb_build_object('table', tg_table_name, 'record', to_jsonb(new)),
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-webhook-secret', secret));
  return new;
exception when others then
  raise warning 'notify_hook: %', sqlerrm; return new;
end $$;

create trigger card_assignees_notify after insert on public.card_assignees for each row execute function private.notify_hook();
create trigger comments_notify after insert on public.comments for each row execute function private.notify_hook();

-- ===== 004_claim_name =====
