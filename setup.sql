create policy st_all on public.card_steps for all to authenticated
  using (in_team(card_team(card_id)))
  with check (in_team(card_team(card_id))
    and (email is null or exists (select 1 from team_members where team_id = card_team(card_id) and team_members.email = card_steps.email)));
